"""Compute the governance scorecard from the live catalogue and write docs/SCORECARD.md.

Every number in the scorecard comes from OpenMetadata's API at run time, so the adoption KPIs in
the operating model are measured, not typed by hand.

Usage:  uv run python scripts/scorecard.py
"""
from __future__ import annotations

import datetime as dt
import pathlib

import requests

ROOT = pathlib.Path(__file__).resolve().parents[1]
OM = "http://localhost:8585/api/v1"
S = requests.Session()
S.headers.update({"Authorization": f"Bearer {(ROOT / '.om_token').read_text().strip()}"})
DB = "erp_postgres.erp"


def get(path, **params):
    r = S.get(OM + path, params=params)
    r.raise_for_status()
    return r.json()


def pct(a, b):
    return f"{100 * a / b:.0f} %" if b else "n/a"


def main():
    tables = get("/tables", database=DB, limit=200, fields="owners,tags,domains,columns,certification")["data"]
    tier1 = [t for t in tables if any(x["tagFQN"] == "Tier.Tier1" for x in t.get("tags", []))]
    governed = [t for t in tables if t.get("owners")]

    def share(group, pred):
        return sum(1 for t in group if pred(t)), len(group)

    own = share(tier1, lambda t: bool(t.get("owners")))
    desc = share(tier1, lambda t: bool((t.get("description") or "").strip()))
    dom = share(tier1, lambda t: bool(t.get("domains")))
    cert = [t["name"] for t in tables if (t.get("certification") or {}).get("tagLabel")]

    cols = [c for t in tables for c in t["columns"]]
    pii = [c for c in cols if any(x["tagFQN"] == "PII.Sensitive" for x in c.get("tags", []))]
    glossary_cols = [c for c in cols if any(x.get("source") == "Glossary" for x in c.get("tags", []))]

    tests = get("/dataQuality/testCases", limit=500, fields="testCaseResult")["data"]
    status = [(t.get("testCaseResult") or {}).get("testCaseStatus", "Not run") for t in tests]
    passed, failed = status.count("Success"), status.count("Failed")
    tested_tables = {t["entityLink"].split("::")[2].rstrip(">") for t in tests}
    incidents = get("/dataQuality/testCases/testCaseIncidentStatus", latest="true", limit=200,
                    startTs=0, endTs=int(dt.datetime.now().timestamp() * 1000))["data"]
    open_inc = [i for i in incidents if i["testCaseResolutionStatusType"] != "Resolved"]

    contracts = get("/dataContracts", limit=100)["data"]
    contract_ok = 0
    for c in contracts:
        r = S.get(f"{OM}/dataContracts/{c['id']}/results/latest")
        if r.ok and r.json().get("contractExecutionStatus") == "Success":
            contract_ok += 1

    edges = col_edges = 0
    for t in tables:
        lin = get("/lineage/getLineage", fqn=t["fullyQualifiedName"], type="table", upstreamDepth=1, downstreamDepth=0)
        up = lin.get("upstreamEdges") or {}
        for e in (up.values() if isinstance(up, dict) else up):
            edges += 1
            col_edges += len(e.get("columns") or [])

    gid = get("/glossaries/name/SupplyChainGlossary")["id"]
    glossary = get("/glossaryTerms", glossary=gid, limit=100)["data"]
    approved = sum(1 for g in glossary if g.get("entityStatus", g.get("status")) == "Approved")

    rows = [
        ("Ownership", "Tier 1 tables with an owner team", pct(*own), f"{own[0]}/{own[1]}", "100 %"),
        ("Ownership", "Tier 1 tables with a domain", pct(*dom), f"{dom[0]}/{dom[1]}", "100 %"),
        ("Documentation", "Tier 1 tables with a description", pct(*desc), f"{desc[0]}/{desc[1]}", "100 %"),
        ("Documentation", "Approved glossary terms", pct(approved, len(glossary)), f"{approved}/{len(glossary)}", "100 %"),
        ("Documentation", "Columns linked to a glossary term", str(len(glossary_cols)), "", ""),
        ("Classification", "Columns tagged as sensitive personal data (PII.Sensitive)", str(len(pii)), "", ""),
        ("Quality", "Tables with data-quality tests", pct(len(tested_tables), len(tables)), f"{len(tested_tables)}/{len(tables)}", "≥ 60 %"),
        ("Quality", "Tests passing", pct(passed, len(tests)), f"{passed}/{len(tests)}", "≥ 95 %"),
        ("Quality", "Open data-quality incidents", str(len(open_inc)), "", "0 older than 10 days"),
        ("Trust", "Certified (Gold) tables", str(len(cert)), ", ".join(sorted(cert)), ""),
        ("Trust", "Data contracts passing validation", pct(contract_ok, len(contracts)), f"{contract_ok}/{len(contracts)}", "100 %"),
        ("Lineage", "Table-level lineage edges", str(edges), "", ""),
        ("Lineage", "Column-level lineage mappings", str(col_edges), "", ""),
    ]

    md = [
        "# Governance Scorecard",
        "",
        f"*Generated by `scripts/scorecard.py` from the live OpenMetadata API on {dt.date.today():%d %B %Y}.*",
        f"*Scope: {len(tables)} tables in `{DB}`, of which {len(governed)} governed and {len(tier1)} Tier 1.*",
        "",
        "| Area | KPI | Value | Detail | Target |",
        "|---|---|---|---|---|",
        *[f"| {a} | {k} | **{v}** | {d} | {g} |" for a, k, v, d, g in rows],
        "",
        "## Data-quality results",
        "",
        "```mermaid",
        "pie showData",
        f'    "Passing" : {passed}',
        f'    "Failing (injected defects)" : {failed}',
        "```",
        "",
        "The failing tests are expected: the synthetic data contains three deliberate defects",
        "(deliveries without goods-issue date, negative stock, a purchase order for an unknown material),",
        "each caught at the raw layer by OpenMetadata and at the staging layer by dbt.",
        "",
    ]
    out = ROOT / "docs" / "SCORECARD.md"
    out.write_text("\n".join(md))
    for a, k, v, d, g in rows:
        print(f"{k:42s} {v:>6s}  {d}")
    print(f"written {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
